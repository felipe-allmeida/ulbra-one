namespace Ulbra.One.Finance.Application.Endpoints.Payables.StageItems;

/// <summary>
/// Payable-grain list for the stage tabs (Entry / Classification / Approval / Reconciled): ONE row per
/// title, with the title total and installment count — unlike <c>ListPayables</c>, which is per-installment
/// for the operational due-date view. The payment stage stays per-installment (you pay parcelas).
/// </summary>
/// <summary>Query-string filters for the stage tabs. Bound via <c>[AsParameters]</c>.</summary>
public sealed record GetPayableStageItemsRequest : PaginationQueryParameters
{
    [SwaggerSchema("Company that owes the payables. Omit for the consolidated view, which only a "
        + "consolidated role may request.")]
    public CompanyId? CompanyId { get; set; }

    [SwaggerSchema("Stage to keep — this is what the tab selection maps to.")]
    public PayableStatus? Status { get; set; }

    [SwaggerSchema("Keep only titles that already have a registered fiscal document, or only those still "
        + "missing one.")]
    public bool? HasFiscalDocument { get; set; }

    [SwaggerSchema("Where the payable came from: typed in by hand, or generated by an approved requisition.")]
    public PayableOrigin? Origin { get; set; }

    [SwaggerSchema("Keep only titles still waiting on the accounting review.")]
    public bool? ReviewPending { get; set; }

    [SwaggerSchema("Free-text search over counterparty name, document number and vendor CNPJ/CPF.")]
    public string? Search { get; set; }
}

public sealed class GetPayableStageItems : IEndpoint
{
    public void Map(IEndpointRouteBuilder builder) =>
        builder.MapGet("stage-items", Handle).WithName("GetPayableStageItems").WithTags("Finance")
            .WithSummary("Lists payables by title for the stage tabs.")
            .WithDescription("One row per TITLE, with the title total and its installment count — the "
                + "grain the entry, classification, approval and reconciliation tabs work at. This is the "
                + "difference from the payable list, which is per installment because paying happens per "
                + "parcela; the payment stage keeps using that one.")
            .RequirePermission(Permissions.PayablesRead).Produces<PaginatedResponse<PayableStageItemResponse>>(StatusCodes.Status200OK)
            .ProducesProblem(StatusCodes.Status403Forbidden);

    private static async Task<IResult> Handle(
        UserContext user,
        [AsParameters] GetPayableStageItemsRequest req,
        IUnitOfWork uow,
        CancellationToken ct)
    {
        var (companyId, status, origin, reviewPending, hasFiscalDocument, search) =
            (req.CompanyId, req.Status, req.Origin, req.ReviewPending, req.HasFiscalDocument, req.Search);

        // Consolidated "all companies" (AEL-906): companyId omitted → across every company, consolidated roles only.
        if (companyId is null && !user.CanSeeConsolidated)
            return ErrorResults.Forbidden("No access to the consolidated view.", ErrorCodes.Payable.ConsolidatedForbidden);
        var cid = companyId?.Value;
        var q = uow.ReadSet<Payable>().Where(p => cid == null || p.CompanyId == cid.Value);
        if (status is { } st) q = q.Where(p => p.Status == st);
        // Origin filter (e.g. the "Adiantamentos" tab of Registro de Despesa: origin=Advance, no status).
        if (origin is { } og) q = q.Where(p => p.Origin == og);

        // AEL-846/854 Contábil post-hoc review: requisition payables that reached Scheduled/Paid without a resolved
        // ledger account (null) or with a low-confidence one (< 0.8) — the accountant classifies them post-hoc. Two
        // ways in: auto-scheduled (AccountedBy "system:req:…"), or released by the Tributário after tax analysis
        // (TaxReviewedBy set, AEL-948) — both schedule WITHOUT a human picking the account, so Contábil must still
        // classify them (the title is forwarded to Accounting). Guarded to Scheduled/Paid so a cancelled payable
        // never lingers. The low-confidence leg only matches LEGACY rows auto-applied before AEL-854; new rows
        // arrive with a null account (suggestion only), so they match the first leg.
        if (reviewPending == true)
            q = q.Where(p => p.Origin == PayableOrigin.Purchase
                             && (p.Status == PayableStatus.Scheduled || p.Status == PayableStatus.Paid)
                             && ((p.AccountedBy != null && p.AccountedBy.StartsWith("system:req:")) || p.TaxReviewedBy != null)
                             && (p.AccountingAccountId == null || p.ClassificationConfidence < 0.8));

        // Free-text search (Contábil "buscar por código ou informações"): matches vendor/description/NF number,
        // plus the requisition code exactly when the term is numeric (OriginRequisitionCode is the friendly #).
        if (!string.IsNullOrWhiteSpace(search))
        {
            var term = search.Trim();
            var codeSearch = int.TryParse(term, out var c) ? c : (int?)null;
            q = q.Where(p => p.CounterpartyName.Contains(term)
                             || p.Description.Contains(term)
                             || (p.DocumentNumber != null && p.DocumentNumber.Contains(term))
                             || (codeSearch != null && p.OriginRequisitionCode == codeSearch));
        }

        // "Has document" = a parsed FiscalDocument (XML) OR a Nota Fiscal attachment, and for Conta Fixa
        // (RequiresFiscalDocument) a Fatura also counts (Fatura OU NF). Mirrors PayableFiscalGate. Correlated
        // EXISTS, all translated to SQL.
        var fiscalDocs = uow.ReadSet<FiscalDocument>();
        var attachments = uow.ReadSet<PayableAttachment>();

        // Project primitives first so the query + pagination translate to SQL; wrap typed IDs in memory.
        var rows = q.Select(p => new
        {
            p.Id,
            p.CompanyId,
            p.CounterpartyName,
            p.Description,
            p.CostCenterId,
            p.CategoryId,
            p.Origin,
            FirstDueDate = p.Installments.Min(i => i.DueDate),
            InstallmentCount = p.Installments.Count,
            p.TotalAmount,
            // Correlated scalar subquery on payable_withholding (FK-indexed); EF wraps the SUM in
            // COALESCE(..., 0), so titles without withholdings project 0. NetTotal (a computed domain
            // property that doesn't translate to SQL) is derived in the mapping below.
            TotalWithheld = p.Withholdings.Sum(w => w.Amount),
            p.Status,
            HasFiscalDocument = fiscalDocs.Any(d => d.PayableId == p.Id)
                || attachments.Any(a => a.PayableId == p.Id && a.Kind == PayableAttachmentKind.FiscalDocument)
                || (p.RequiresFiscalDocument && attachments.Any(a => a.PayableId == p.Id && a.Kind == PayableAttachmentKind.Invoice)),
            p.AccountingAccountId,
            p.SuggestedAccountingAccountId,
            p.ClassificationConfidence,
            p.ClassificationRationale,
            p.OriginRequisitionCode,
        });

        // Optional pendency filter (e.g. Pendências "Nota Fiscal" tab: PendingAccounting + no NF). EF
        // translates HasFiscalDocument to WHERE [NOT] EXISTS. Absent => unchanged behavior for all stages.
        // The false branch means "NF pendency", not "fact: no NF" — Advance payables (adiantamento) are
        // exempt from the NF gate, so they never count as pending. The response flag stays factual.
        if (hasFiscalDocument is { } hasNf)
            rows = hasNf
                ? rows.Where(x => x.HasFiscalDocument)
                : rows.Where(x => !x.HasFiscalDocument && x.Origin != PayableOrigin.Advance);

        var page = await rows.OrderBy(x => x.FirstDueDate).ToPaginatedAsync(req, ct);
        return TypedResults.Ok(page.Map(x => new PayableStageItemResponse(
            new PayableId(x.Id), new CompanyId(x.CompanyId), x.CounterpartyName, x.Description, new CostCenterId(x.CostCenterId),
            x.CategoryId == null ? null : new ExpenseCategoryId(x.CategoryId.Value),
            x.FirstDueDate, x.InstallmentCount, x.TotalAmount, x.TotalWithheld, x.TotalAmount - x.TotalWithheld,
            x.Status, x.Origin, x.HasFiscalDocument,
            x.AccountingAccountId == null ? null : new LedgerAccountId(x.AccountingAccountId.Value),
            x.SuggestedAccountingAccountId == null ? null : new LedgerAccountId(x.SuggestedAccountingAccountId.Value),
            x.ClassificationConfidence, x.ClassificationRationale, x.OriginRequisitionCode)));
    }
}
